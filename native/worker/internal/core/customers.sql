CREATE TABLE IF NOT EXISTS wb_customers (
 cid VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 data JSON NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS wb_customer_identifiers (
 kind VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 scope VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 value VARCHAR(191) COLLATE utf8mb4_0900_bin NOT NULL,
 cid VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 PRIMARY KEY(kind,scope,value),
 INDEX wb_customer_identifiers_cid(cid),
 FOREIGN KEY(cid) REFERENCES wb_customers(cid)
) ENGINE=InnoDB;
